#!/usr/bin/env bash
#
# One icon, every platform.
#
# assets/icon/icon.png is the only icon the project keeps. This script turns it
# into everything each platform wants, so replacing that one file and re-running
# it is all it takes to re-brand the app:
#
#   * Android — launcher mipmaps for every density, plus an adaptive icon
#     (foreground + background) for Android 8 and newer.
#   * Windows — windows/runner/resources/app_icon.ico, which Runner.rc embeds
#     into the .exe.
#   * Linux — a window icon is set from the same PNG at runtime (see
#     linux/runner/my_application.cc); with --install-linux this also registers
#     a desktop entry and a hicolor icon, which is what a Wayland taskbar
#     matches a running window against.
#
# Usage:
#   tool/app_icons.sh [--install-linux [<bundle-executable>]]
#
# Needs ImageMagick (`magick`, or `convert` on older releases).
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source_png="$root/assets/icon/icon.png"
android_res="$root/android/app/src/main/res"
windows_res="$root/windows/runner/resources"

if [[ ! -f "$source_png" ]]; then
  echo "missing $source_png" >&2
  exit 1
fi

if command -v magick >/dev/null 2>&1; then
  im=magick
elif command -v convert >/dev/null 2>&1; then
  im=convert
else
  echo "ImageMagick is required (magick or convert)" >&2
  exit 1
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# The artwork is not exactly square, and a launcher icon has to be. Pad it with
# the colour of its own corner, so the padding is invisible whatever the
# artwork's background happens to be.
corner="$("$im" "$source_png" -format '%[pixel:p{0,0}]' info:)"
read -r red green blue <<<"$(printf '%s' "$corner" |
  sed -E 's/.*\(([0-9]+),([0-9]+),([0-9]+).*/\1 \2 \3/')"
background="rgb($red,$green,$blue)"
printf -v background_hex '#%02X%02X%02X' "$red" "$green" "$blue"

"$im" "$source_png" -background "$background" -gravity center \
  -extent "$("$im" "$source_png" -format '%[fx:max(w,h)]x%[fx:max(w,h)]' info:)" \
  "$work/square.png"

echo "Android launcher icons"
# Legacy launcher icons, one per density.
for entry in mdpi:48 hdpi:72 xhdpi:96 xxhdpi:144 xxxhdpi:192; do
  density="${entry%%:*}"
  size="${entry##*:}"
  mkdir -p "$android_res/mipmap-$density"
  "$im" "$work/square.png" -resize "${size}x${size}" \
    "$android_res/mipmap-$density/ic_launcher.png"
  echo "  mipmap-$density/ic_launcher.png (${size}px)"
done

# Adaptive icon: a 108dp canvas whose middle 72dp is guaranteed to survive the
# launcher's mask, so the drawing is scaled down a little to sit inside it.
echo "Android adaptive icon"
for entry in mdpi:108 hdpi:162 xhdpi:216 xxhdpi:324 xxxhdpi:432; do
  density="${entry%%:*}"
  canvas="${entry##*:}"
  inner=$((canvas * 85 / 100))
  "$im" "$work/square.png" -resize "${inner}x${inner}" -background none \
    -gravity center -extent "${canvas}x${canvas}" \
    "$android_res/mipmap-$density/ic_launcher_foreground.png"
  echo "  mipmap-$density/ic_launcher_foreground.png (${canvas}px canvas)"
done

mkdir -p "$android_res/mipmap-anydpi-v26" "$android_res/values"
cat >"$android_res/mipmap-anydpi-v26/ic_launcher.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/app_icons.sh: adaptive icon from assets/icon/icon.png. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
XML
cat >"$android_res/values/ic_launcher_background.xml" <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/app_icons.sh: the artwork's own background colour. -->
<resources>
    <color name="ic_launcher_background">$background_hex</color>
</resources>
XML
echo "  mipmap-anydpi-v26/ic_launcher.xml + values/ic_launcher_background.xml ($background_hex)"

echo "Windows icon"
"$im" "$work/square.png" -define icon:auto-resize=256,128,64,48,32,16 \
  "$windows_res/app_icon.ico"
echo "  windows/runner/resources/app_icon.ico"

if [[ "${1:-}" == "--install-linux" ]]; then
  executable="${2:-}"
  if [[ -z "$executable" ]]; then
    for candidate in \
      "$root/build/linux/x64/release/bundle/pchat_app" \
      "$root/build/linux/x64/debug/bundle/pchat_app"; do
      [[ -x "$candidate" ]] && executable="$candidate" && break
    done
  fi

  app_id="io.github.shepu1.pchat"
  icon_dir="$HOME/.local/share/icons/hicolor"
  entry_dir="$HOME/.local/share/applications"

  echo "Linux desktop entry"
  for size in 256 512; do
    mkdir -p "$icon_dir/${size}x${size}/apps"
    "$im" "$work/square.png" -resize "${size}x${size}" \
      "$icon_dir/${size}x${size}/apps/$app_id.png"
  done
  mkdir -p "$entry_dir"
  cat >"$entry_dir/$app_id.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=PCHAT
Comment=Private peer-to-peer chat
Exec=${executable:-pchat_app}
Icon=$app_id
Terminal=false
Categories=Network;InstantMessaging;
# Matches the Wayland app id GTK takes from the runner's APPLICATION_ID, which
# is how the taskbar finds this entry for the running window.
StartupWMClass=$app_id
EOF
  echo "  $entry_dir/$app_id.desktop"
  echo "  $icon_dir/{256x256,512x512}/apps/$app_id.png"
  command -v update-desktop-database >/dev/null 2>&1 &&
    update-desktop-database "$entry_dir" >/dev/null 2>&1 || true
fi

echo "done"
